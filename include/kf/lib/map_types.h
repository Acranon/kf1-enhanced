enum class KfMapCellKind : u8 {
    KF_MAP_CELL_BLOCKED = 0,
    KF_MAP_CELL_FLOOR = 1,

    KF_MAP_CELL_X_GE_Z = 2,
    KF_MAP_CELL_SUM_LE_SIZE = 3,
    KF_MAP_CELL_Z_GE_X = 4,
    KF_MAP_CELL_SUM_GE_SIZE = 5,
    KF_MAP_CELL_STEP = 6
}; using enum KfMapCellKind;

constexpr bool map_cell_has_full_floor(KfMapCellKind kind)
{
    return kind == KF_MAP_CELL_FLOOR || kind == KF_MAP_CELL_STEP;
}

